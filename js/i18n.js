  const supported = ['en', 'es', 'fr', 'ru'];
  let language = 'en';
  try {
    const saved = localStorage.getItem('dh_language');
    if (supported.indexOf(saved) >= 0) language = saved;
  } catch (e) {}

  function interpolate(value, vars) {
    if (!vars) return value;
    return value.replace(/\{(\w+)\}/g, function (_, key) {
      return vars[key] === undefined ? '{' + key + '}' : String(vars[key]);
    });
  }

  function t(key, vars) {
    const table = dictionaries[language] || dictionaries.en;
    const value = table[key] !== undefined ? table[key] :
      (dictionaries.en[key] !== undefined ? dictionaries.en[key] : key);
    return interpolate(value, vars);
  }

  function setLanguage(next) {
    if (supported.indexOf(next) < 0 || next === language) return false;
    language = next;
    try { localStorage.setItem('dh_language', language); } catch (e) {}
    if (document.documentElement) document.documentElement.lang = language;
    window.dispatchEvent(new CustomEvent('languagechange', { detail: { language: language } }));
    return true;
  }

  function cycle(direction) {
    const index = supported.indexOf(language);
    const next = supported[(index + (direction < 0 ? -1 : 1) + supported.length) % supported.length];
    setLanguage(next);
    return language;
  }

  function languageName(code) {
    const table = dictionaries[code] || dictionaries.en;
    return table['language.name'];
  }

  if (document.documentElement) document.documentElement.lang = language;

  window.I18n = {
    t: t,
    getLanguage: function () { return language; },
    setLanguage: setLanguage,
    cycle: cycle,
    supported: function () { return supported.slice(); },
    languageName: languageName
  };
